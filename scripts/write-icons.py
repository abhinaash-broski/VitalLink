def scaled(name: str, size: int) -> str:
    sw = round(1.9 * 24 / size, 3)
    attrs = f'stroke="currentColor" stroke-width="{sw:g}" stroke-linecap="round" stroke-linejoin="round"'
    body = "\n".join(f'<path d="{d}" {attrs}/>' for d in MASTERS[name])
    return (
        f'<svg width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
        f'xmlns="http://www.w3.org/2000/svg">\n{body}\n</svg>\n'
    )


def component(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("-"))


def registry(names: list[str], suffix: str, comment: str) -> str:
    lines = [
        "// Generated by scripts/write-icons.py. Do not edit.",
        comment,
    ]
    lines += [f'import {component(n)} from "../../../../packages/assets/icons/{n}.svg{suffix}";' for n in names]
    lines.append("")
    lines.append("export const ICONS = {")
    lines += [f'  "{n}": {component(n)},' for n in names]
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    files = dict(ICONS)
    for name, sizes in USES.items():
        for size in sizes:
            files.setdefault(f"{name}-{size}", scaled(name, size))
    for name, body in files.items():
        (OUT / f"{name}.svg").write_text(body, newline="\n")
    names = sorted(files)
    root = OUT.parent.parent.parent
    (root / "apps/web/src/components/icons.gen.ts").write_text(
        registry(names, "?react", "// Strokes are currentColor; colour comes from a token at the call site."), newline="\n")
    (root / "apps/mobile/src/components/icons.gen.ts").write_text(
        registry(names, "", "// Strokes are currentColor; react-native-svg's `color` prop tints them."), newline="\n")
    print(f"wrote {len(files)} icons to {OUT} and both registries")


if __name__ == "__main__":
    main()
